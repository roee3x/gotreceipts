/**
 * The text of the hook file that "gotreceipts install" writes into the repository's hooks folder.
 *
 * The file is a small shell script. Git runs hook files through a shell on every system,
 * Windows included, so one script serves all of them.
 */

/** The line that marks a hook file as written by this tool. A file without it is someone else's. */
export const HOOK_MARKER = '# gotreceipts:managed-hook';

/** The name an older hook is kept under. The managed hook runs it first. */
export function keptName(hookName: string): string {
  return `${hookName}.local`;
}

/** Where the tool is on this machine: the program that runs it, and its entry file. */
export interface Launcher {
  readonly node: string;
  readonly cli: string;
}

/** A path as a shell reads it: forward slashes, inside single quotes. */
function shellQuote(path: string): string {
  return `'${path.replace(/\\/g, '/').replace(/'/g, `'\\''`)}'`;
}

function shellUnquote(quoted: string): string {
  return quoted.slice(1, -1).replace(/'\\''/g, "'");
}

/**
 * How the tool is started by hand on this machine, as one line a shell or a person can use.
 * Undefined when the path of the tool holds a character that would break out of the quotes.
 */
export function startLine(launcher: Launcher): string | undefined {
  const cli = launcher.cli.replace(/\\/g, '/');
  if (/["$`]/.test(cli)) return undefined;
  return `node "${cli}"`;
}

/** True when the tool runs from a folder that will not stay, such as the one "npx" downloads into. */
export function looksTemporary(cliPath: string): boolean {
  return /[\\/]_npx[\\/]/.test(cliPath);
}

/**
 * The hook script for one git hook.
 *
 * It keeps what git piped to it, hands it first to an older hook if one was kept, and then to
 * the tool. It calls the tool at the exact place it was installed from, so the version that
 * wrote the hook is the version that runs. When the tool is gone, the hook blocks and says so.
 */
export function hookScript(hookName: string, launcher: Launcher): string {
  const kept = keptName(hookName);
  return [
    '#!/bin/sh',
    `${HOOK_MARKER} ${hookName}`,
    '# Written by "gotreceipts install". Do not edit this file: run "gotreceipts install" again.',
    '# To remove it, run "gotreceipts uninstall".',
    '',
    `node=${shellQuote(launcher.node)}`,
    `cli=${shellQuote(launcher.cli)}`,
    'hooks=$(dirname "$0")',
    'input=$(cat)',
    '',
    `# A hook that was already here is kept as ${kept} and runs first, with the same input.`,
    `if [ -x "$hooks/${kept}" ]; then`,
    `  printf '%s\\n' "$input" | "$hooks/${kept}" "$@" || exit $?`,
    'fi',
    '',
    'if [ ! -f "$cli" ]; then',
    `  echo "gotreceipts ${hookName}: CANNOT CHECK: the tool is no longer at $cli" >&2`,
    '  echo "This is blocked. A check that could not run is never treated as a pass." >&2',
    '  echo "Run \\"gotreceipts install\\" again from where the tool is now." >&2',
    '  exit 2',
    'fi',
    '[ -x "$node" ] || node=node',
    `printf '%s\\n' "$input" | "$node" "$cli" hook ${hookName} "$@"`,
    '',
  ].join('\n');
}

/** True when a hook file was written by this tool. */
export function isManagedHook(text: string): boolean {
  return text.split('\n').some((line) => line.startsWith(HOOK_MARKER));
}

/** The entry file a managed hook calls, or undefined when the file does not say. */
export function cliOfHook(text: string): string | undefined {
  const line = text.split('\n').find((candidate) => /^cli='.*'$/.test(candidate));
  return line === undefined ? undefined : shellUnquote(line.slice('cli='.length));
}
